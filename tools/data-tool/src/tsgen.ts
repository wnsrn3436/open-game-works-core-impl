/**
 * The server generated code `GameData` (`server/generated/data/game_data.ts`) and the DEV accessor `GameDataDev`
 * (`server/dev/generated/data/game_data_dev.ts`), by `server-core` `## generated code`.
 */
import { compareBytes } from './diag.ts';
import { columnTypeName, refTargetType, tableTypeNames, VECTOR_MESSAGES, vectorMessage, type GenField, type GenMessage, type GenTable, type TargetSchema, type TargetTable } from './schema.ts';
import { isCommaType, type ColumnType } from './types.ts';

export const HEADER = '// Generated by the data tool. Do not edit.';

/** What the accessors need: the ID value of each row they read, 0 when data has no such row. */
export interface AccessorInput {
  /** `game_setting` rows of the build target: ID name, ID value, `data_type`. */
  settings: { name: string; idValue: number; type: ColumnType }[];
  /** `ReservedId` keys: ID name and ID value (0 when data has no row). */
  reservedIds: { name: string; idValue: number }[];
  /** `ReservedString` keys: ID name and ID value (0 when data has no row). */
  reservedStrings: { name: string; idValue: number }[];
}

/**
 * The protobuf reader of the generated code. It reaches globals outside the `data` skill's list of global names
 * (`DataView`, `TextDecoder`, `ReadonlyMap`) through `globalThis`, so a data enum of such a name does not hide them.
 */
const READER = `const decoder = new globalThis.TextDecoder();

class Reader {
  pos = 0;
  failed = false;
  private readonly buf: Uint8Array;
  private readonly view: globalThis.DataView;

  constructor(buf: Uint8Array) {
    this.buf = buf;
    this.view = new globalThis.DataView(buf.buffer, buf.byteOffset, buf.byteLength);
  }

  fail(): void {
    this.failed = true;
  }

  varint(): bigint {
    let result = 0n;
    let shift = 0n;
    for (let i = 0; i < 10; i += 1) {
      const b = this.buf[this.pos];
      if (b === undefined) break;
      this.pos += 1;
      result |= BigInt(b & 0x7f) << shift;
      if ((b & 0x80) === 0) return BigInt.asUintN(64, result);
      shift += 7n;
    }
    this.failed = true;
    return 0n;
  }

  /** The end position of a length-delimited value that starts here. */
  enter(end: number): number {
    const n = Number(this.varint());
    const to = this.pos + n;
    if (to > end) {
      this.failed = true;
      return this.pos;
    }
    return to;
  }

  skip(wire: number, end: number): void {
    if (wire === 0) this.varint();
    else if (wire === 1) this.advance(8, end);
    else if (wire === 2) this.pos = this.enter(end);
    else if (wire === 5) this.advance(4, end);
    else this.failed = true;
  }

  int32(wire: number): number {
    if (wire !== 0) this.failed = true;
    return this.failed ? 0 : Number(BigInt.asIntN(32, this.varint()));
  }

  int64(wire: number): bigint {
    if (wire !== 0) this.failed = true;
    return this.failed ? 0n : BigInt.asIntN(64, this.varint());
  }

  bool(wire: number): boolean {
    return this.int64(wire) !== 0n;
  }

  float(wire: number, end: number): number {
    if (wire !== 5 || this.pos + 4 > end) this.failed = true;
    if (this.failed) return 0;
    const v = this.view.getFloat32(this.pos, true);
    this.pos += 4;
    return v;
  }

  double(wire: number, end: number): number {
    if (wire !== 1 || this.pos + 8 > end) this.failed = true;
    if (this.failed) return 0;
    const v = this.view.getFloat64(this.pos, true);
    this.pos += 8;
    return v;
  }

  bytes(wire: number, end: number): Uint8Array {
    if (wire !== 2) this.failed = true;
    if (this.failed) return new Uint8Array();
    const to = this.enter(end);
    const b = this.buf.slice(this.pos, to);
    this.pos = to;
    return b;
  }

  string(wire: number, end: number): string {
    return decoder.decode(this.bytes(wire, end));
  }

  /** Reads a repeated scalar field, packed or not. */
  repeated<T>(wire: number, end: number, scalar: number, read: (wire: number, end: number) => T, list: T[]): void {
    if (wire !== 2 || scalar === 2) {
      list.push(read(wire, end));
      return;
    }
    const to = this.enter(end);
    while (this.pos < to && !this.failed) list.push(read(scalar, to));
    this.pos = to;
  }

  message<T>(wire: number, end: number, made: T, fields: Fields<T>): T {
    if (wire !== 2) this.failed = true;
    if (this.failed) return made;
    const to = this.enter(end);
    decode(this, to, made, fields);
    this.pos = to;
    return made;
  }

  private advance(n: number, end: number): void {
    if (this.pos + n > end) this.failed = true;
    else this.pos += n;
  }
}

type Fields<T> = globalThis.ReadonlyMap<number, (r: Reader, wire: number, end: number, m: T) => void>;

function decode<T>(r: Reader, end: number, m: T, fields: Fields<T>): T {
  while (r.pos < end && !r.failed) {
    const tag = Number(r.varint());
    const read = fields.get(tag >>> 3);
    if (read) read(r, tag & 7, end, m);
    else r.skip(tag & 7, end);
  }
  return m;
}

class TableReader {
  failed = false;
  private readonly files: globalThis.ReadonlyMap<string, Uint8Array>;

  constructor(files: globalThis.ReadonlyMap<string, Uint8Array>) {
    this.files = files;
  }

  rows<T>(file: string, make: () => T, fields: Fields<T>): T[] {
    const bytes = this.files.get(file);
    if (bytes === undefined) {
      this.failed = true;
      return [];
    }
    const rows: T[] = [];
    const r = new Reader(bytes);
    decode(r, bytes.length, rows, new Map([[1, (x: Reader, wire: number, end: number, list: T[]) => { list.push(x.message(wire, end, make(), fields)); }]]));
    if (r.failed) this.failed = true;
    return rows;
  }
}

`;

/** Helper functions of the accessors; a file has the ones it uses. */
const HELPERS: Readonly<Record<string, string>> = {
  parse_int: `function parse_int(text: string): number {
  const v = Number.parseInt(text, 10);
  return Number.isNaN(v) ? 0 : v;
}
`,
  parse_long: `function parse_long(text: string): bigint {
  return /^-?[0-9]+$/.test(text) ? BigInt(text) : 0n;
}
`,
  parse_real: `function parse_real(text: string): number {
  const v = Number(text);
  return Number.isNaN(v) ? 0 : v;
}
`,
  split_list: `function split_list(text: string, comma: boolean): string[] {
  if (text === "") return [];
  return comma ? text.split(",") : text.split("\\n");
}
`,
};

export function q(text: string): string {
  return JSON.stringify(text);
}

/** The TypeScript type of a field of a column type. */
const SCALAR_TS: Readonly<Record<string, string>> = {
  int: 'number', id: 'number', requirement: 'number', float: 'number', double: 'number',
  long: 'bigint', datetime: 'bigint', duration: 'bigint', bool: 'boolean',
};

export function tsType(tables: ReadonlyMap<string, GenTable>, t: ColumnType, itemName: string): string {
  const s = refTargetType(tables, t);
  switch (s.k) {
    case 'enum': return s.enumType;
    case 'vector': return vectorMessage(s.size, s.elem);
    case 'array': return `${tsType(tables, s.elem, itemName)}[]`;
    case 'array2': return `${tsType(tables, s.elem, itemName)}[][]`;
    case 'bundle': return s.itemAmount ? 'CoreContract.ItemAmount[]' : `${itemName}[]`;
    default: return SCALAR_TS[s.k] ?? 'string';
  }
}

function tsDefault(tables: ReadonlyMap<string, GenTable>, t: ColumnType, type: string): string {
  const s = refTargetType(tables, t);
  if (s.k === 'array' || s.k === 'array2' || s.k === 'bundle') return '[]';
  if (s.k === 'vector') return `new ${type}()`;
  if (s.k === 'enum') return `${s.enumType}.None`;
  if (type === 'number') return '0';
  if (type === 'bigint') return '0n';
  if (type === 'boolean') return 'false';
  return '""';
}

function doc(comment: string, indent: string): string[] {
  if (comment === '') return [];
  return [`${indent}/** ${comment.replace(/\*\//g, '*\\/').replace(/\r?\n/g, ' ')} */`];
}

function classOf(name: string, fields: { name: string; type: string; init: string; comment: string }[]): string[] {
  const body = fields.flatMap((f) => [...doc(f.comment, '  '), `  ${f.name}: ${f.type} = ${f.init};`]);
  return [`export class ${name} {`, ...body, '}', ''];
}

/** The `(wire, end)` reader expression of one scalar of a column type. */
function scalarRead(tables: ReadonlyMap<string, GenTable>, t: ColumnType): { read: string; wire: number } {
  const s = refTargetType(tables, t);
  switch (s.k) {
    case 'int': case 'id': case 'requirement': return { read: 'r.int32(w)', wire: 0 };
    case 'long': case 'datetime': case 'duration': return { read: 'r.int64(w)', wire: 0 };
    case 'float': return { read: 'r.float(w, e)', wire: 5 };
    case 'double': return { read: 'r.double(w, e)', wire: 1 };
    case 'bool': return { read: 'r.bool(w)', wire: 0 };
    case 'enum': return { read: `r.int32(w) as ${s.enumType}`, wire: 0 };
    case 'vector': {
      const name = vectorMessage(s.size, s.elem);
      return { read: `r.message(w, e, new ${name}(), ${constName(name)})`, wire: 2 };
    }
    default: return { read: 'r.string(w, e)', wire: 2 };
  }
}

function repeatedRead(tables: ReadonlyMap<string, GenTable>, elem: ColumnType, list: string): string {
  const { read, wire } = scalarRead(tables, elem);
  return `r.repeated(w, e, ${String(wire)}, ${/\be\b/.test(read) ? '(w, e)' : '(w)'} => ${read}, ${list})`;
}

function fieldReader(tables: ReadonlyMap<string, GenTable>, table: string, f: GenField): string {
  const t = f.type;
  const target = `m.${f.name}`;
  let body: string;
  if (t.k === 'array') body = repeatedRead(tables, t.elem, target);
  else if (t.k === 'array2') {
    const list = columnTypeName(table, f.name, t) ?? '';
    body = `${target}.push(r.message(w, e, [] as ${tsType(tables, t.elem, '')}[], ${constName(list)}))`;
  } else if (t.k === 'bundle' && t.itemAmount) {
    body = `{ const v = CoreContract.ItemAmount.decode(r.bytes(w, e)); if (v === null) r.fail(); else ${target}.push(v); }`;
  } else if (t.k === 'bundle') {
    const item = columnTypeName(table, f.name, t) ?? '';
    body = `${target}.push(r.message(w, e, new ${item}(), ${constName(item)}))`;
  } else body = `${target} = ${scalarRead(tables, t).read}`;
  return `  [${String(f.number)}, ${lambda(body.startsWith('{') ? body.slice(1, -1).trim() : `${body};`)}],`;
}

/** A field reader `(r, w, e, m) => { body }`; a parameter the body does not use starts with `_`. */
function lambda(body: string): string {
  const uses = (name: string): boolean => new RegExp(`\\b${name}\\b`).test(body);
  const params = ['r', 'w', 'e', 'm'].map((p) => (uses(p) ? p : `_${p}`));
  return `(${params.join(', ')}) => { ${body} }`;
}

/** The field reader table of a message: the message name kept as it is, so different messages never share it. */
function constName(message: string): string {
  return `${message}_FIELDS`;
}

function fieldsConst(tables: ReadonlyMap<string, GenTable>, table: string, m: GenMessage, type: string): string[] {
  const lines = m.fields.map((f) => fieldReader(tables, table, f));
  return [`const ${constName(m.name)}: Fields<${type}> = new Map([`, ...lines, ']);', ''];
}

function listFieldsConst(tables: ReadonlyMap<string, GenTable>, m: GenMessage): string[] {
  const f = m.fields[0] as GenField;
  const elem = tsType(tables, f.type, '');
  return [`const ${constName(m.name)}: Fields<${elem}[]> = new Map([`, `  [1, ${lambda(`${repeatedRead(tables, f.type, 'm')};`)}],`, ']);', ''];
}

function vectorCode(used: string): string[] {
  const out: string[] = [];
  for (const name of VECTOR_MESSAGES) {
    const size = Number(name[6]);
    const isInt = name.endsWith('Int');
    const comps = ['x', 'y', 'z', 'w'].slice(0, size);
    out.push(...classOf(name, comps.map((c) => ({ name: c, type: 'number', init: '0', comment: '' }))));
    const read = isInt ? 'r.int32(w)' : 'r.float(w, e)';
    if (!used.includes(constName(name))) continue;
    out.push(`const ${constName(name)}: Fields<${name}> = new Map([`, ...comps.map((c, i) => `  [${String(i + 1)}, ${lambda(`m.${c} = ${read};`)}],`), ']);', '');
  }
  return out;
}

function tableCode(tables: ReadonlyMap<string, GenTable>, t: TargetTable): string[] {
  const names = tableTypeNames(t.table.name, t.rowMessage.fields);
  const row = t.rowMessage.name;
  const out: string[] = [];
  out.push(...classOf(row, t.rowMessage.fields.map((f) => {
    const type = tsType(tables, f.type, names.columns.get(f.name) ?? '');
    return { name: f.name, type, init: tsDefault(tables, f.type, type), comment: f.comment };
  })));
  for (const m of t.extraMessages) {
    if (m.name.endsWith('List')) {
      out.push(...listFieldsConst(tables, m));
      continue;
    }
    out.push(...classOf(m.name, m.fields.map((f) => {
      const type = tsType(tables, f.type, '');
      return { name: f.name, type, init: tsDefault(tables, f.type, type), comment: '' };
    })));
    out.push(...fieldsConst(tables, t.table.name, m, m.name));
  }
  out.push(...fieldsConst(tables, t.table.name, t.rowMessage, row));
  out.push(...containerCode(names.table, row, t.table.keyed));
  return out;
}

function containerCode(container: string, row: string, keyed: boolean): string[] {
  const empty = `${row}_EMPTY`;
  const lines = [`const ${empty} = new ${row}();`, '', `export class ${container} {`, `  private readonly rows: readonly ${row}[];`];
  if (keyed) {
    lines.push(`  private readonly by_id: globalThis.ReadonlyMap<number, ${row}>;`, '', `  constructor(rows: readonly ${row}[]) {`, '    this.rows = rows;', '    this.by_id = new Map(rows.map((r) => [r.id, r]));', '  }', '');
  } else {
    lines.push(`  private readonly by_id: globalThis.ReadonlyMap<number, readonly ${row}[]>;`, '', `  constructor(rows: readonly ${row}[]) {`, '    this.rows = rows;',
      `    const by_id = new Map<number, ${row}[]>();`, '    for (const r of rows) {', '      const list = by_id.get(r.id);', '      if (list) list.push(r);', '      else by_id.set(r.id, [r]);', '    }', '    this.by_id = by_id;', '  }', '');
  }
  lines.push(`  all_rows(): readonly ${row}[] {`, '    return this.rows;', '  }', '', `  empty_row(): ${row} {`, `    return ${empty};`, '  }', '');
  if (keyed) {
    lines.push(`  get_row(id: number): ${row} {`, `    return this.by_id.get(id) ?? ${empty};`, '  }', '', '  has_row(id: number): boolean {', '    return this.by_id.has(id);', '  }');
  } else {
    lines.push(`  get_rows(id: number): readonly ${row}[] {`, '    return this.by_id.get(id) ?? NO_ROWS;', '  }', '', '  has_rows(id: number): boolean {', '    return this.by_id.has(id);', '  }');
  }
  lines.push('}', '');
  return lines;
}

function enumCode(schema: TargetSchema): string[] {
  const out: string[] = [];
  for (const e of schema.enums) {
    const members = [['None', 0] as const, ...e.elements.map((el) => [el.element, el.value] as const)].map(([n, v]) => `  ${n}: ${String(v)},`);
    out.push(`export const ${e.type} = {`, ...members, '} as const;', `export type ${e.type} = (typeof ${e.type})[keyof typeof ${e.type}];`, '');
  }
  return out;
}

/** The expression that reads a built `game_setting` value text `s` as its `data_type`. */
export function settingParse(tables: ReadonlyMap<string, GenTable>, t: ColumnType, s: string): string {
  const x = refTargetType(tables, t);
  switch (x.k) {
    case 'int': case 'id': case 'requirement': return `parse_int(${s})`;
    case 'long': case 'datetime': case 'duration': return `parse_long(${s})`;
    case 'float': case 'double': return `parse_real(${s})`;
    case 'bool': return `${s} === "true"`;
    case 'enum': return `parse_int(${s}) as ${x.enumType}`;
    case 'vector': {
      const name = vectorMessage(x.size, x.elem);
      const comps = ['x', 'y', 'z', 'w'].slice(0, x.size).map((c, i) => `v.${c} = parse_real(p[${String(i)}] ?? "");`).join(' ');
      return `((p: string[]) => { const v = new ${name}(); ${comps} return v; })(split_list(${s}, true))`;
    }
    case 'array': return `split_list(${s}, ${String(isCommaType(x.elem))}).map((x) => ${settingParse(tables, x.elem, 'x')})`;
    default: return s;
  }
}

/**
 * The accessor classes. An accessor is named after an ID name, `[a-z0-9_]+`, so the field that keeps the table is
 * `Table`, a name no accessor takes. It is `protected` and not `#Table`, so a class without accessors still compiles.
 */
function accessorCode(tables: ReadonlyMap<string, GenTable>, a: AccessorInput): string[] {
  const out: string[] = ['export class GameSettingAccessor {', '  protected readonly Table: GameSettingTable;', '', '  constructor(table: GameSettingTable) {', '    this.Table = table;', '  }'];
  for (const s of [...a.settings].sort((x, y) => compareBytes(x.name, y.name))) {
    const name = s.name.slice(1, -1);
    out.push('', `  ${name}(): ${tsType(tables, s.type, '')} {`, `    return ${settingParse(tables, s.type, `this.Table.get_row(${String(s.idValue)}).value`)};`, '  }');
  }
  out.push('}', '', 'export class ReservedIdAccessor {', '  protected readonly Table: ReservedIdTable;', '', '  constructor(table: ReservedIdTable) {', '    this.Table = table;', '  }');
  for (const r of [...a.reservedIds].sort((x, y) => compareBytes(x.name, y.name))) {
    out.push('', `  ${r.name.slice(1, -1)}(): number {`, r.idValue === 0 ? '    return 0;' : `    return parse_int(this.Table.get_row(${String(r.idValue)}).value);`, '  }');
  }
  out.push('}', '', 'export class ReservedStringAccessor {', '  protected readonly Table: ReservedStringTable;', '', '  constructor(table: ReservedStringTable) {', '    this.Table = table;', '  }');
  for (const r of [...a.reservedStrings].sort((x, y) => compareBytes(x.name, y.name))) {
    out.push('', `  ${r.name.slice(1, -1)}(): string {`, r.idValue === 0 ? '    return "";' : `    return this.Table.get_row(${String(r.idValue)}).text;`, '  }');
  }
  out.push('}', '');
  return out;
}

function dataSetCode(schema: TargetSchema): string[] {
  const props = schema.tables.map((t) => tableTypeNames(t.table.name, []).table);
  const out = ['export class DataSet {', ...props.map((p) => `  readonly ${p}: ${p};`), '  readonly GameSetting: GameSettingAccessor;', '  readonly ReservedId: ReservedIdAccessor;', '  readonly ReservedString: ReservedStringAccessor;', '', '  constructor(r: TableReader) {'];
  for (const t of schema.tables) {
    const container = tableTypeNames(t.table.name, []).table;
    out.push(`    this.${container} = new ${container}(r.rows(${q(`${t.table.name}.bin`)}, () => new ${t.rowMessage.name}(), ${constName(t.rowMessage.name)}));`);
  }
  out.push('    this.GameSetting = new GameSettingAccessor(this.GameSettingTable);', '    this.ReservedId = new ReservedIdAccessor(this.ReservedIdTable);', '    this.ReservedString = new ReservedStringAccessor(this.ReservedStringTable);', '  }', '}', '');
  out.push('/** Fills every container and accessor from the table binaries by file name; null when one does not decode. */',
    'export function load_data_set(files: globalThis.ReadonlyMap<string, Uint8Array>): DataSet | null {', '  const r = new TableReader(files);', '  const set = new DataSet(r);', '  return r.failed ? null : set;', '}');
  return out;
}

/** The translation binary load entry point (`Translation` and `TranslationEntry` of the data proto). */
const TRANSLATION_CODE = [
  'const TranslationEntry_FIELDS: Fields<{ key: string; text: string }> = new Map([',
  '  [1, (r: Reader, w: number, e: number, m: { key: string; text: string }) => { m.key = r.string(w, e); }],',
  '  [2, (r: Reader, w: number, e: number, m: { key: string; text: string }) => { m.text = r.string(w, e); }],',
  ']);',
  '',
  '/** The texts of a translation binary by build translation key; null when the bytes do not decode as `Translation`. */',
  'export function load_translation(bytes: Uint8Array): globalThis.ReadonlyMap<string, string> | null {',
  '  const r = new Reader(bytes);',
  '  const texts = new Map<string, string>();',
  '  decode(r, bytes.length, texts, new Map([[1, (x: Reader, w: number, e: number, m: Map<string, string>) => {',
  '    const entry = x.message(w, e, { key: "", text: "" }, TranslationEntry_FIELDS);',
  '    m.set(entry.key, entry.text);',
  '  }]]));',
  '  return r.failed ? null : texts;',
  '}',
  '',
];

/** `server/generated/data/game_data.ts`. */
export function gameDataTs(schema: TargetSchema, tables: ReadonlyMap<string, GenTable>, accessors: AccessorInput): string {
  const body: string[] = [];
  for (const t of schema.tables) body.push(...tableCode(tables, t));
  body.push(...accessorCode(tables, accessors), ...dataSetCode(schema), '', ...TRANSLATION_CODE);
  const text = body.join('\n');
  const helpers = Object.entries(HELPERS).filter(([name]) => text.includes(`${name}(`)).map(([, code]) => code);
  const lines = [HEADER];
  if (schema.usesItemAmount) lines.push('import * as CoreContract from "../contract/core_contract.ts";');
  lines.push('', ...enumCode(schema), READER, ...helpers, ...vectorCode(text), text.includes('NO_ROWS') ? 'const NO_ROWS: readonly never[] = [];\n' : '', text);
  return `${lines.join('\n').trimEnd()}\n`;
}

/** `server/dev/generated/data/game_data_dev.ts`. */
export function gameDataDevTs(ids: ReadonlyMap<string, number>): string {
  const entries = [...ids].sort((a, b) => compareBytes(a[0], b[0])).map(([name, value]) => `  [${q(name)}, ${String(value)}],`);
  return [
    HEADER, '', 'const ID_VALUES: ReadonlyMap<string, number> = new Map([', ...entries, ']);', '',
    'const ID_NAMES: ReadonlyMap<number, string> = new Map([...ID_VALUES].map(([name, value]) => [value, name]));', '',
    '/** The ID value of an ID name; 0 when there is none. */', 'export function find_id_value(id_name: string): number {', '  return ID_VALUES.get(id_name) ?? 0;', '}', '',
    '/** The ID name of an ID value; an empty string when there is none. */', 'export function find_id_name(id_value: number): string {', '  return ID_NAMES.get(id_value) ?? "";', '}', '',
  ].join('\n');
}
