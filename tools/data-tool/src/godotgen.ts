/**
 * The Godot client generated code (`client-core` Godot `### generated code`): `GameData`, the accessors `GameSetting`,
 * `ReservedId`, `ReservedString`, `ReservedSound` and the DEV accessor `GameDataDev`. Paths are under the Godot
 * project (`client/`).
 */
import { compareBytes } from './diag.ts';
import { columnTypeName, refTargetType, tableTypeNames, type GenField, type GenMessage, type GenTable, type TargetSchema, type TargetTable } from './schema.ts';
import { isCommaType, upperSnake, type ColumnType } from './types.ts';

export const GODOT_DATA_DIR = 'generated/data';
export const GODOT_DEV_DATA_DIR = 'dev/generated/data';

const HEADER = '# Generated by the data tool. Do not edit.';

/** What the client accessors need: the ID value of each row they read, 0 when data has no such row. */
export interface GodotAccessorInput {
  /** `game_setting` rows of the Client build target: ID name, ID value, `data_type`. */
  settings: { name: string; idValue: number; type: ColumnType }[];
  reservedIds: { name: string; idValue: number }[];
  reservedStrings: { name: string; idValue: number }[];
  reservedSounds: { name: string; idValue: number }[];
}

function q(text: string): string {
  return JSON.stringify(text);
}

/** Wire reader of the generated code: the contract code's reader. */
const READER = 'ContractMessage._WireReader';

/** GDScript vector type of a vector column type. */
function vectorType(size: number, elem: 'int' | 'float'): string {
  return `Vector${String(size)}${elem === 'int' ? 'i' : ''}`;
}

/** GDScript scalar type of a column type that is not an array (`### generated code` data type table). */
function scalarType(tables: ReadonlyMap<string, GenTable>, t: ColumnType): string {
  const s = refTargetType(tables, t);
  switch (s.k) {
    case 'int': case 'long': case 'id': case 'requirement': case 'datetime': case 'duration': return 'int';
    case 'float': case 'double': return 'float';
    case 'bool': return 'bool';
    case 'enum': return s.enumType;
    case 'vector': return vectorType(s.size, s.elem);
    default: return 'String';
  }
}

/** Packed array or typed array of a repeated scalar (`### generated code` proto table). */
function listType(tables: ReadonlyMap<string, GenTable>, elem: ColumnType): string {
  const s = refTargetType(tables, elem);
  switch (s.k) {
    case 'int': case 'id': case 'requirement': case 'enum': return 'PackedInt32Array';
    case 'long': case 'datetime': case 'duration': return 'PackedInt64Array';
    case 'float': return 'PackedFloat32Array';
    case 'double': return 'PackedFloat64Array';
    case 'bool': return 'Array[bool]';
    case 'vector': return `Array[${vectorType(s.size, s.elem)}]`;
    default: return 'PackedStringArray';
  }
}

/** GDScript field type of a column type; `item` is the `<Table><Column>Item` class of a bundle column. */
export function gdType(tables: ReadonlyMap<string, GenTable>, t: ColumnType, item: string): string {
  const s = refTargetType(tables, t);
  if (s.k === 'array') return listType(tables, s.elem);
  if (s.k === 'array2') {
    const inner = listType(tables, s.elem);
    return inner.startsWith('Packed') ? `Array[${inner}]` : 'Array';
  }
  if (s.k === 'bundle') return s.itemAmount ? 'Array[CoreContract.ItemAmount]' : `Array[${item}]`;
  return scalarType(tables, s);
}

function gdDefault(tables: ReadonlyMap<string, GenTable>, t: ColumnType, type: string): string {
  const s = refTargetType(tables, t);
  if (type.startsWith('Packed')) return `${type}()`;
  if (type.startsWith('Array')) return '[]';
  if (s.k === 'vector') return `${type}.ZERO`;
  if (s.k === 'enum') return `${s.enumType}.NONE`;
  if (type === 'int') return '0';
  if (type === 'float') return '0.0';
  if (type === 'bool') return 'false';
  return '""';
}

/** Lines that read one value of a scalar column type from reader `r` with wire type `wire`, as an expression. */
function scalarRead(tables: ReadonlyMap<string, GenTable>, t: ColumnType): string {
  const s = refTargetType(tables, t);
  switch (s.k) {
    case 'int': case 'id': case 'requirement': return 'r.int32(wire)';
    case 'long': case 'datetime': case 'duration': return 'r.int64(wire)';
    case 'float': return 'r.float32(wire)';
    case 'double': return 'r.float64(wire)';
    case 'bool': return 'r.boolean(wire)';
    case 'enum': return `r.int32(wire) as ${s.enumType}`;
    case 'vector': return `_read_${vectorType(s.size, s.elem).toLowerCase()}(r.bytes(wire))`;
    default: return 'r.string(wire)';
  }
}

/** Packed read of a repeated scalar, or null when it is read one value at a time. */
function packedRead(tables: ReadonlyMap<string, GenTable>, elem: ColumnType): string | null {
  const s = refTargetType(tables, elem);
  switch (s.k) {
    case 'int': case 'id': case 'requirement': case 'enum': return 'r.int32_list(wire)';
    case 'long': case 'datetime': case 'duration': return 'r.int64_list(wire)';
    case 'float': return 'r.float32_list(wire)';
    case 'double': return 'r.float64_list(wire)';
    case 'bool': return 'r.boolean_list(wire)';
    default: return null;
  }
}

/** Statement that adds the repeated values of one field occurrence to `target`. */
function repeatedRead(tables: ReadonlyMap<string, GenTable>, elem: ColumnType, target: string): string {
  const packed = packedRead(tables, elem);
  return packed === null ? `${target}.append(${scalarRead(tables, elem)})` : `${target}.append_array(${packed})`;
}

function readFuncName(kind: string, ...names: string[]): string {
  return `_read_${names.join('_')}_${kind}`;
}

/** Field reading lines of one field of a row or item message, as `match` branch bodies. */
function fieldRead(tables: ReadonlyMap<string, GenTable>, table: string, f: GenField, target: string): string[] {
  const t = f.type;
  if (t.k === 'array') return [repeatedRead(tables, t.elem, `${target}.${f.name}`)];
  if (t.k === 'array2') return [`${target}.${f.name}.append(${readFuncName('list', table, f.name)}(r.bytes(wire)))`];
  if (t.k === 'bundle' && t.itemAmount) {
    return ['var amount: CoreContract.ItemAmount = CoreContract.ItemAmount.new()', 'if not amount.decode(r.bytes(wire)):', '\t_failed = true', `${target}.${f.name}.append(amount)`];
  }
  if (t.k === 'bundle') return [`${target}.${f.name}.append(${readFuncName('item', table, f.name)}(r.bytes(wire)))`];
  return [`${target}.${f.name} = ${scalarRead(tables, t)}`];
}

function matchLoop(body: (f: GenField) => string[], fields: readonly GenField[]): string[] {
  const out = [`\tvar r: ${READER} = ${READER}.new(bytes)`, '\twhile r.more():', '\t\tvar tag: int = r.tag()', '\t\tvar wire: int = tag & 7'];
  if (fields.length === 0) return [...out, '\t\tr.skip(wire)', '\tif r.failed:', '\t\t_failed = true'];
  out.push('\t\tmatch tag >> 3:');
  for (const f of fields) out.push(`\t\t\t${String(f.number)}:`, ...body(f).map((l) => `\t\t\t\t${l}`));
  out.push('\t\t\t_:', '\t\t\t\tr.skip(wire)', '\tif r.failed:', '\t\t_failed = true');
  return out;
}

function classLines(name: string, fields: { name: string; type: string; init: string; comment: string }[]): string[] {
  const body = fields.flatMap((f) => [...(f.comment === '' ? [] : f.comment.split(/\r?\n/).map((l) => `\t## ${l}`.trimEnd())), `\tvar ${f.name}: ${f.type} = ${f.init}`]);
  return ['', '', `class ${name} extends RefCounted:`, ...(body.length === 0 ? ['\tpass'] : body)];
}

function messageFields(tables: ReadonlyMap<string, GenTable>, table: string, m: GenMessage, comments: boolean): { name: string; type: string; init: string; comment: string }[] {
  return m.fields.map((f) => {
    const type = gdType(tables, f.type, columnTypeName(table, f.name, f.type) ?? '');
    return { name: f.name, type, init: gdDefault(tables, f.type, type), comment: comments ? f.comment : '' };
  });
}

/** Column types that are key columns of `DataCore` derived containers, with how their key value reads. */
function isKeyType(tables: ReadonlyMap<string, GenTable>, t: ColumnType): boolean {
  const s = refTargetType(tables, t);
  return s.k === 'int' || s.k === 'long' || s.k === 'id' || s.k === 'enum';
}

function containerLines(t: TargetTable): string[] {
  const names = tableTypeNames(t.table.name, []);
  const row = names.row;
  const lines = ['', '', `class ${names.table} extends RefCounted:`, `\tstatic var _rows: Array[${row}] = []`, `\tstatic var _empty: ${row} = ${row}.new()`];
  if (t.table.keyed) lines.push(`\tstatic var _by_id: Dictionary[int, ${row}] = {}`);
  else lines.push('\tstatic var _by_id: Dictionary[int, Array] = {}', `\tstatic var _no_rows: Array[${row}] = []`);
  lines.push('', '', `\tstatic func all_rows() -> Array[${row}]:`, '\t\treturn _rows', '', '', `\tstatic func empty_row() -> ${row}:`, '\t\treturn _empty');
  if (t.table.keyed) {
    lines.push(
      '', '', `\tstatic func get_row(id: int) -> ${row}:`, '\t\tif not _by_id.has(id):', '\t\t\treturn _empty', '\t\treturn _by_id[id]',
      '', '', '\tstatic func has_row(id: int) -> bool:', '\t\treturn _by_id.has(id)',
      '', '', `\tstatic func _fill(rows: Array[${row}]) -> void:`, '\t\t_rows = rows', '\t\t_by_id = {}', `\t\tfor row: ${row} in rows:`, '\t\t\t_by_id[row.id] = row',
    );
  } else {
    lines.push(
      '', '', `\tstatic func get_rows(id: int) -> Array[${row}]:`, '\t\tif not _by_id.has(id):', '\t\t\treturn _no_rows', `\t\tvar rows: Array[${row}] = _by_id[id]`, '\t\treturn rows',
      '', '', '\tstatic func has_rows(id: int) -> bool:', '\t\treturn _by_id.has(id)',
      '', '', `\tstatic func _fill(rows: Array[${row}]) -> void:`, '\t\t_rows = rows', '\t\t_by_id = {}', `\t\tfor row: ${row} in rows:`,
      '\t\t\tif not _by_id.has(row.id):', `\t\t\t\tvar group: Array[${row}] = []`, '\t\t\t\t_by_id[row.id] = group', `\t\t\tvar rows_of_id: Array[${row}] = _by_id[row.id]`, '\t\t\trows_of_id.append(row)',
    );
  }
  lines.push('', '', '\tstatic func _clear() -> void:', `\t\t_rows = []`, '\t\t_by_id = {}');
  return lines;
}

function tableReadLines(tables: ReadonlyMap<string, GenTable>, t: TargetTable): string[] {
  const table = t.table.name;
  const row = t.rowMessage.name;
  const out: string[] = [];
  for (const m of t.extraMessages) {
    const column = m.name.endsWith('List') ? t.rowMessage.fields.find((f) => columnTypeName(table, f.name, f.type) === m.name) : undefined;
    if (column !== undefined && column.type.k === 'array2') {
      const type = gdType(tables, { k: 'array', elem: column.type.elem }, '');
      out.push('', '', `static func ${readFuncName('list', table, column.name)}(bytes: PackedByteArray) -> ${type}:`, `\tvar values: ${type} = ${gdDefault(tables, { k: 'array', elem: column.type.elem }, type)}`);
      const elem = column.type.elem;
      out.push(...matchLoop(() => [repeatedRead(tables, elem, 'values')], m.fields), '\treturn values');
      continue;
    }
    const field = t.rowMessage.fields.find((f) => columnTypeName(table, f.name, f.type) === m.name);
    if (field === undefined) continue;
    out.push('', '', `static func ${readFuncName('item', table, field.name)}(bytes: PackedByteArray) -> ${m.name}:`, `\tvar item: ${m.name} = ${m.name}.new()`);
    out.push(...matchLoop((f) => fieldRead(tables, table, f, 'item'), m.fields), '\treturn item');
  }
  out.push('', '', `static func ${readFuncName('row', table)}(bytes: PackedByteArray) -> ${row}:`, `\tvar row: ${row} = ${row}.new()`);
  out.push(...matchLoop((f) => fieldRead(tables, table, f, 'row'), t.rowMessage.fields), '\treturn row');
  out.push('', '', `static func ${readFuncName('rows', table)}(bytes: PackedByteArray) -> Array[${row}]:`, `\tvar rows: Array[${row}] = []`);
  const rowsField = [{ name: 'rows', number: 1 } as GenField];
  out.push(...matchLoop(() => [`rows.append(${readFuncName('row', table)}(r.bytes(wire)))`], rowsField), '\treturn rows');
  return out;
}

const VECTORS: readonly { size: 2 | 3 | 4; elem: 'int' | 'float' }[] = [
  { size: 2, elem: 'int' }, { size: 3, elem: 'int' }, { size: 4, elem: 'int' }, { size: 2, elem: 'float' }, { size: 3, elem: 'float' }, { size: 4, elem: 'float' },
];

function vectorReadLines(used: string): string[] {
  const out: string[] = [];
  for (const v of VECTORS) {
    const type = vectorType(v.size, v.elem);
    const name = `_read_${type.toLowerCase()}`;
    if (!used.includes(`${name}(`)) continue;
    const comps = ['x', 'y', 'z', 'w'].slice(0, v.size);
    out.push('', '', `static func ${name}(bytes: PackedByteArray) -> ${type}:`, `\tvar value: ${type} = ${type}.ZERO`);
    const read = v.elem === 'int' ? 'r.int32(wire)' : 'r.float32(wire)';
    out.push(...matchLoop((f) => [`value.${f.name} = ${read}`], comps.map((c, i) => ({ name: c, number: i + 1 }) as GenField)), '\treturn value');
  }
  return out;
}

function enumLines(schema: TargetSchema): string[] {
  const out: string[] = [];
  for (const e of schema.enums) {
    out.push('', `enum ${e.type} {`, '\tNONE = 0,', ...e.elements.map((el) => `\t${upperSnake(el.element)} = ${String(el.value)},`), '}');
  }
  return out;
}

function keyColumnLines(tables: ReadonlyMap<string, GenTable>, schema: TargetSchema): string[] {
  const isKey = ['', '', '## True when the table has a key column of that name.', 'static func is_key_column(table: String, column: String) -> bool:', '\tmatch table:'];
  const value = ['', '', '## The key column value of a row: enum value, ID value or integer.', 'static func key_value(table: String, column: String, row: RefCounted) -> int:', '\tmatch table:'];
  for (const t of schema.tables) {
    const keys = t.rowMessage.fields.filter((f) => isKeyType(tables, f.type));
    if (keys.length === 0) continue;
    isKey.push(`\t\t${q(t.table.name)}:`, `\t\t\treturn column in PackedStringArray([${keys.map((f) => q(f.name)).join(', ')}])`);
    value.push(`\t\t${q(t.table.name)}:`, `\t\t\tvar typed_row: ${t.rowMessage.name} = row as ${t.rowMessage.name}`, '\t\t\tif typed_row == null:', '\t\t\t\treturn 0', '\t\t\tmatch column:');
    for (const f of keys) value.push(`\t\t\t\t${q(f.name)}:`, `\t\t\t\t\treturn typed_row.${f.name}`);
  }
  if (isKey.length === 5) isKey.push('\t\t_:', '\t\t\treturn false');
  if (value.length === 5) value.push('\t\t_:', '\t\t\treturn 0');
  return [...isKey, '\treturn false', ...value, '\treturn 0'];
}

function loadLines(schema: TargetSchema): string[] {
  const out = [
    '', '', '## Fills every container and accessor from the table binaries by file name. Nothing is filled and the result is',
    '## `false` when a table binary is missing or does not decode.', 'static func load_tables(files: Dictionary[String, PackedByteArray]) -> bool:',
  ];
  for (const t of schema.tables) out.push(`\tif not files.has(${q(`${t.table.name}.bin`)}):`, '\t\treturn false');
  out.push('\t_failed = false');
  for (const t of schema.tables) out.push(`\tvar rows_${t.table.name}: Array[${t.rowMessage.name}] = ${readFuncName('rows', t.table.name)}(files[${q(`${t.table.name}.bin`)}])`);
  out.push('\tif _failed:', '\t\treturn false');
  for (const t of schema.tables) out.push(`\t${tableTypeNames(t.table.name, []).table}._fill(rows_${t.table.name})`);
  out.push('\treturn true', '', '', '## Empties every container and so every accessor.', 'static func clear() -> void:');
  for (const t of schema.tables) out.push(`\t${tableTypeNames(t.table.name, []).table}._clear()`);
  if (schema.tables.length === 0) out.push('\tpass');
  out.push('', '', '## The rows of a table in `all_rows()` order; an empty list for a table there is not.', 'static func table_rows(table: String) -> Array[RefCounted]:', '\tvar rows: Array[RefCounted] = []', '\tmatch table:');
  for (const t of schema.tables) out.push(`\t\t${q(t.table.name)}:`, `\t\t\trows.assign(${tableTypeNames(t.table.name, []).table}.all_rows())`);
  if (schema.tables.length === 0) out.push('\t\t_:', '\t\t\tpass');
  out.push('\treturn rows', '', '', '## The empty row of a table; `null` for a table there is not.', 'static func table_empty_row(table: String) -> RefCounted:', '\tmatch table:');
  for (const t of schema.tables) out.push(`\t\t${q(t.table.name)}:`, `\t\t\treturn ${tableTypeNames(t.table.name, []).table}.empty_row()`);
  if (schema.tables.length === 0) out.push('\t\t_:', '\t\t\tpass');
  out.push('\treturn null');
  return out;
}

/** `client/generated/data/game_data.gd`. */
export function gameDataGd(schema: TargetSchema, tables: ReadonlyMap<string, GenTable>): string {
  const body: string[] = [];
  for (const t of schema.tables) {
    body.push(...classLines(t.rowMessage.name, messageFields(tables, t.table.name, t.rowMessage, true)));
    for (const m of t.extraMessages) if (!m.name.endsWith('List')) body.push(...classLines(m.name, messageFields(tables, t.table.name, m, false)));
    body.push(...containerLines(t));
  }
  const reads = schema.tables.flatMap((t) => tableReadLines(tables, t));
  const text = [...body, ...reads].join('\n');
  const lines = [
    HEADER, 'class_name GameData', 'extends RefCounted', ...enumLines(schema), '', '## True when a read of the load running now did not decode.', 'static var _failed: bool = false',
    ...body, ...loadLines(schema), ...keyColumnLines(tables, schema), ...reads, ...vectorReadLines(text),
  ];
  return `${lines.join('\n')}\n`;
}

/** The expression that reads a built `game_setting` value text `s` as its `data_type`. */
function settingParse(tables: ReadonlyMap<string, GenTable>, t: ColumnType, s: string): string {
  const x = refTargetType(tables, t);
  switch (x.k) {
    case 'int': case 'long': case 'id': case 'requirement': case 'datetime': case 'duration': return `_parse_int(${s})`;
    case 'float': case 'double': return `_parse_real(${s})`;
    case 'bool': return `${s} == "true"`;
    case 'enum': return `_parse_int(${s}) as GameData.${x.enumType}`;
    case 'vector': return `_parse_${vectorType(x.size, x.elem).toLowerCase()}(${s})`;
    default: return s;
  }
}

/** Lines of the accessor body for an `array<T>` setting read from text `s`. */
function settingArrayLines(tables: ReadonlyMap<string, GenTable>, elem: ColumnType, type: string, s: string): string[] {
  const init = type.startsWith('Packed') ? `${type}()` : '[]';
  return [`\tvar values: ${type} = ${init}`, `\tfor part: String in _parse_split(${s}, ${String(isCommaType(elem))}):`, `\t\tvalues.append(${settingParse(tables, elem, 'part')})`, '\treturn values'];
}

const SETTING_HELPERS = [
  '', '', 'static func _parse_int(text: String) -> int:', '\treturn text.to_int() if text.is_valid_int() else 0',
  '', '', 'static func _parse_real(text: String) -> float:', '\treturn text.to_float() if text.is_valid_float() else 0.0',
  '', '', 'static func _parse_split(text: String, comma: bool) -> PackedStringArray:', '\tif text.is_empty():', '\t\treturn PackedStringArray()', '\treturn text.split("," if comma else "\\n")',
  '', '', 'static func _parse_part(parts: PackedStringArray, index: int) -> String:', '\treturn parts[index] if index < parts.size() else ""',
];

function vectorParseLines(used: string): string[] {
  const out: string[] = [];
  for (const v of VECTORS) {
    const type = vectorType(v.size, v.elem);
    const name = `_parse_${type.toLowerCase()}`;
    if (!used.includes(`${name}(`)) continue;
    const parse = v.elem === 'int' ? '_parse_int' : '_parse_real';
    const args = ['x', 'y', 'z', 'w'].slice(0, v.size).map((_c, i) => `${parse}(_parse_part(parts, ${String(i)}))`).join(', ');
    out.push('', '', `static func ${name}(text: String) -> ${type}:`, '\tvar parts: PackedStringArray = _parse_split(text, true)', `\treturn ${type}(${args})`);
  }
  return out;
}

/** GDScript type of a `game_setting` accessor outside `GameData`: an enum type is qualified. */
function settingType(tables: ReadonlyMap<string, GenTable>, t: ColumnType): string {
  const type = gdType(tables, t, '');
  return refTargetType(tables, t).k === 'enum' ? `GameData.${type}` : type;
}

/** `client/generated/data/game_setting.gd`. The test values `GameDataDev` sets come first. */
export function gameSettingGd(tables: ReadonlyMap<string, GenTable>, a: GodotAccessorInput): string {
  const settings = [...a.settings].sort((x, y) => compareBytes(x.name, y.name));
  const vars: string[] = [];
  const funcs: string[] = [];
  const clear: string[] = [];
  for (const s of settings) {
    const name = s.name.slice(1, -1);
    const type = settingType(tables, s.type);
    const value = `GameData.GameSettingTable.get_row(${String(s.idValue)}).value`;
    const init = refTargetType(tables, s.type).k === 'enum' ? `${type}.NONE` : gdDefault(tables, s.type, type);
    vars.push(`static var _has_test_${name}: bool = false`, `static var _test_${name}: ${type} = ${init}`);
    clear.push(`\t_has_test_${name} = false`);
    funcs.push('', '', `static func ${name}() -> ${type}:`, `\tif _has_test_${name}:`, `\t\treturn _test_${name}`);
    const x = refTargetType(tables, s.type);
    if (x.k === 'array') funcs.push(...settingArrayLines(tables, x.elem, type, value));
    else funcs.push(`\treturn ${settingParse(tables, s.type, value)}`);
  }
  const text = funcs.join('\n');
  const lines = [HEADER, 'class_name GameSetting', 'extends RefCounted', '## `game_setting` values of the Client build target by accessor.', '', ...vars, ...funcs];
  lines.push('', '', '## Drops every test value `GameDataDev` set.', 'static func _clear_tests() -> void:', ...(clear.length === 0 ? ['\tpass'] : clear));
  lines.push(...SETTING_HELPERS, ...vectorParseLines(text));
  return `${lines.join('\n')}\n`;
}

function reservedGd(cls: string, doc: string, rows: readonly { name: string; idValue: number }[], type: 'int' | 'String', read: (id: number) => string): string {
  const lines = [HEADER, `class_name ${cls}`, 'extends RefCounted', `## ${doc}`];
  for (const r of [...rows].sort((x, y) => compareBytes(x.name, y.name))) {
    lines.push('', '', `static func ${r.name.slice(1, -1)}() -> ${type}:`, `\treturn ${r.idValue === 0 ? (type === 'int' ? '0' : '""') : read(r.idValue)}`);
  }
  return `${lines.join('\n')}\n`;
}

/** `client/dev/generated/data/game_data_dev.gd`. */
export function gameDataDevGd(tables: ReadonlyMap<string, GenTable>, ids: ReadonlyMap<string, number>, a: GodotAccessorInput): string {
  const entries = [...ids].sort((x, y) => compareBytes(x[0], y[0])).map(([name, value]) => `\t${q(name)}: ${String(value)},`);
  const lines = [
    HEADER, 'class_name GameDataDev', 'extends RefCounted', '## DEV accessor: ID names and ID values, and `GameSetting` test values.', '',
    'static var _ids: Dictionary[String, int] = {', ...entries, '}', 'static var _names: Dictionary[int, String] = {}',
    '', '', '## The ID value of an ID name; 0 when there is none.', 'static func find_id_value(id_name: String) -> int:', '\treturn _ids.get(id_name, 0)',
    '', '', '## The ID name of an ID value; an empty string when there is none.', 'static func find_id_name(id_value: int) -> String:',
    '\tif _names.is_empty():', '\t\tfor id_name: String in _ids:', '\t\t\t_names[_ids[id_name]] = id_name', '\treturn _names.get(id_value, "")',
  ];
  for (const s of [...a.settings].sort((x, y) => compareBytes(x.name, y.name))) {
    const name = s.name.slice(1, -1);
    lines.push('', '', `static func set_setting_${name}(value: ${settingType(tables, s.type)}) -> void:`, `\tGameSetting._test_${name} = value`, `\tGameSetting._has_test_${name} = true`);
  }
  lines.push('', '', '## Drops every `GameSetting` test value.', 'static func clear_settings() -> void:', '\tGameSetting._clear_tests()');
  return `${lines.join('\n')}\n`;
}

/** The Godot generated files by path under the Godot project. */
export function godotDataFiles(schema: TargetSchema, tables: ReadonlyMap<string, GenTable>, ids: ReadonlyMap<string, number>, a: GodotAccessorInput): Map<string, string> {
  const files = new Map<string, string>();
  files.set(`${GODOT_DATA_DIR}/game_data.gd`, gameDataGd(schema, tables));
  files.set(`${GODOT_DATA_DIR}/game_setting.gd`, gameSettingGd(tables, a));
  files.set(`${GODOT_DATA_DIR}/reserved_id.gd`, reservedGd('ReservedId', 'ID values of the reserved IDs.', a.reservedIds, 'int', (id) => `GameData.ReservedIdTable.get_row(${String(id)}).value.to_int()`));
  files.set(`${GODOT_DATA_DIR}/reserved_string.gd`, reservedGd('ReservedString', 'Build translation keys of the reserved strings.', a.reservedStrings, 'String', (id) => `GameData.ReservedStringTable.get_row(${String(id)}).text`));
  files.set(`${GODOT_DATA_DIR}/reserved_sound.gd`, reservedGd('ReservedSound', 'Resource keys of the reserved sounds.', a.reservedSounds, 'String', (id) => `GameData.ReservedSoundTable.get_row(${String(id)}).sound`));
  files.set(`${GODOT_DEV_DATA_DIR}/game_data_dev.gd`, gameDataDevGd(tables, ids, a));
  return files;
}

