/** Types of each client name space in declaration order: `GameContract` holds only the client type set. */
export function clientNamespaces(model: Model, sets: TypeSets): Record<Namespace, TypeDef[]> {
  const roots = sets.byNamespace.GameContract.filter((d) => d.file === null || CLIENT_FILES.has(d.file.name));
  const client = new Set(reach(roots));
  return {
    CoreContract: sets.byNamespace.CoreContract,
    GameContract: sets.byNamespace.GameContract.filter((d) => client.has(d)),
    CoreCheatContract: sets.byNamespace.CoreCheatContract,
    GameCheatContract: sets.byNamespace.GameCheatContract,
  };
}

/** UserState kinds of a name space in `## UserState` kind order. */
function userStateKinds(types: readonly TypeDef[]): MessageDef[] {
  return orderedKinds(types).filter((d) => kindStore(d) === 'user_state');
}

function zeroValue(def: EnumDef): string {
  return (def.values.find((v) => v.number === 0) ?? def.values[0])?.name ?? '';
}

function quote(text: string): string {
  return JSON.stringify(text);
}

const SCALAR_TYPE: Readonly<Record<string, string>> = { int32: 'int', int64: 'int', float: 'float', double: 'float', bool: 'bool', string: 'String', bytes: 'PackedByteArray' };
const SCALAR_DEFAULT: Readonly<Record<string, string>> = { int32: '0', int64: '0', float: '0.0', double: '0.0', bool: 'false', string: '""', bytes: 'PackedByteArray()' };
const LIST_TYPE: Readonly<Record<string, string>> = {
  int32: 'PackedInt32Array', int64: 'PackedInt64Array', float: 'PackedFloat32Array', double: 'PackedFloat64Array',
  string: 'PackedStringArray', bool: 'Array[bool]', bytes: 'Array[PackedByteArray]',
};
/** `ContractMessage` write helper of a singular scalar and of a repeated scalar, by proto type. */
const PUT: Readonly<Record<string, readonly [string, string]>> = {
  int32: ['_put_int32', '_put_int32_list'], int64: ['_put_int64', '_put_int64_list'], float: ['_put_float', '_put_float_list'],
  double: ['_put_double', '_put_double_list'], bool: ['_put_bool', '_put_bool_list'], string: ['_put_string', '_put_string_list'],
  bytes: ['_put_bytes', '_put_bytes_list'],
};
/** `ContractMessage._WireReader` read of a singular scalar, and of a packable repeated scalar, by proto type. */
const READ: Readonly<Record<string, readonly [string, string | null]>> = {
  int32: ['int32', 'int32_list'], int64: ['int64', 'int64_list'], float: ['float32', 'float32_list'], double: ['float64', 'float64_list'],
  bool: ['boolean', 'boolean_list'], string: ['string', null], bytes: ['bytes', null],
};

/** Proto type key of a field: the scalar, `enum` or `message`. */
function protoKind(field: FieldDef): string {
  const t = field.type;
  return t.kind === 'scalar' ? t.scalar : t.kind;
}

/** Function-scope variable names of a message's generated methods: snake_case, none of them a field name of that message. */
interface Locals {
  readonly out: string;
  readonly other: string;
  readonly reader: string;
  readonly tag: string;
  readonly wire: string;
  readonly item: string;
}

function messageLocals(def: MessageDef): Locals {
  const fields = new Set(def.fields.map((f) => f.name));
  const free = (base: string): string => {
    let name = base;
    for (let n = 2; fields.has(name); n += 1) name = `${base}_${String(n)}`;
    return name;
  };
  return { out: free('out'), other: free('other'), reader: free('reader'), tag: free('tag'), wire: free('wire'), item: free('item') };
}

class Writer {
  private readonly ns: Namespace;
  private readonly namespaceOf: ReadonlyMap<TypeDef, Namespace>;

  constructor(ns: Namespace, namespaceOf: ReadonlyMap<TypeDef, Namespace>) {
    this.ns = ns;
    this.namespaceOf = namespaceOf;
  }

  /** Reference to a type from this name space's file. */
  ref(def: TypeDef): string {
    const ns = this.namespaceOf.get(def) ?? 'GameContract';
    return ns === this.ns ? def.name : `${ns}.${def.name}`;
  }

  fieldType(field: FieldDef): string {
    const t = field.type;
    if (t.kind === 'scalar') return field.repeated ? (LIST_TYPE[t.scalar] ?? '') : (SCALAR_TYPE[t.scalar] ?? '');
    if (t.kind === 'enum') return field.repeated ? 'PackedInt32Array' : this.ref(t.def);
    if (t.kind === 'message') return field.repeated ? `Array[${this.ref(t.def)}]` : this.ref(t.def);
    return 'int';
  }

  fieldDefault(field: FieldDef): string {
    const t = field.type;
    if (field.repeated) return t.kind === 'message' || (t.kind === 'scalar' && (t.scalar === 'bool' || t.scalar === 'bytes')) ? '[]' : `${this.fieldType(field)}()`;
    if (t.kind === 'scalar') return SCALAR_DEFAULT[t.scalar] ?? '0';
    if (t.kind === 'enum') return `${this.ref(t.def)}.${zeroValue(t.def)}`;
    return t.kind === 'message' ? 'null' : '0';
  }

  encodeLines(field: FieldDef, v: Locals): string[] {
    const t = field.type;
    const n = String(field.number);
    if (t.kind === 'message') {
      if (!field.repeated) return [`_put_message(${v.out}, ${n}, ${field.name})`];
      return [`for ${v.item}: ${this.ref(t.def)} in ${field.name}:`, `\t_put_message_item(${v.out}, ${n}, ${v.item})`];
    }
    const kind = t.kind === 'enum' ? 'int32' : protoKind(field);
    const put = PUT[kind];
    if (put === undefined) return [];
    return [`${field.repeated ? put[1] : put[0]}(${v.out}, ${n}, ${field.name})`];
  }

  /** Lines of one `match` branch body that read the field from the reader with the wire type. */
  decodeLines(field: FieldDef, v: Locals): string[] {
    const t = field.type;
    const bytes = `${v.reader}.bytes(${v.wire})`;
    if (t.kind === 'message') {
      const cls = this.ref(t.def);
      if (field.repeated) {
        return [`var ${v.item}: ${cls} = ${cls}.new()`, `if not _merge_child(${v.item}, ${bytes}):`, '\treturn false', `${field.name}.append(${v.item})`];
      }
      return [`if ${field.name} == null:`, `\t${field.name} = ${cls}.new()`, `if not _merge_child(${field.name}, ${bytes}):`, '\treturn false'];
    }
    if (t.kind === 'enum') {
      if (field.repeated) return [`${field.name}.append_array(${v.reader}.int32_list(${v.wire}))`];
      return [`${field.name} = ${v.reader}.int32(${v.wire}) as ${this.ref(t.def)}`];
    }
    const read = READ[protoKind(field)];
    if (read === undefined) return [`${v.reader}.skip(${v.wire})`];
    if (!field.repeated) return [`${field.name} = ${v.reader}.${read[0]}(${v.wire})`];
    if (read[1] !== null) return [`${field.name}.append_array(${v.reader}.${read[1]}(${v.wire}))`];
    return [`${field.name}.append(${v.reader}.${read[0]}(${v.wire}))`];
  }
}

function indent(lines: readonly string[], tabs: number): string[] {
  const pad = '\t'.repeat(tabs);
  return lines.map((l) => (l === '' ? '' : `${pad}${l}`));
}

function enumLines(def: EnumDef): string[] {
  return ['', `enum ${def.name} {`, ...def.values.map((v) => `\t${v.name} = ${String(v.number)},`), '}'];
}

function messageLines(w: Writer, def: MessageDef, rpc: RpcDef | null): string[] {
  const base = rpc === null ? 'ContractMessage' : 'ContractRequest';
  const v = messageLocals(def);
  const body: string[] = [];
  for (const field of def.fields) body.push(`var ${field.name}: ${w.fieldType(field)} = ${w.fieldDefault(field)}`);
  if (def.fields.length > 0) body.push('');
  body.push('', 'func encode() -> PackedByteArray:', `\tvar ${v.out}: PackedByteArray = PackedByteArray()`);
  for (const field of def.fields) body.push(...indent(w.encodeLines(field, v), 1));
  body.push(`\treturn ${v.out}`, '', '', 'func decode(_bytes: PackedByteArray) -> bool:', '\t_reset()', '\treturn _merge(_bytes)');
  body.push('', '', 'func copy_from(_source: ContractMessage) -> void:', `\tif not (_source is ${def.name}):`, '\t\treturn');
  if (def.fields.length > 0) {
    body.push(`\tvar ${v.other}: ${def.name} = _source as ${def.name}`);
    for (const field of def.fields) body.push(`\t${field.name} = ${v.other}.${field.name}`);
  }
  body.push('', '', 'func _reset() -> void:');
  if (def.fields.length === 0) body.push('\tpass');
  for (const field of def.fields) body.push(`\t${field.name} = ${w.fieldDefault(field)}`);
  body.push(
    '', '', 'func _merge(_bytes: PackedByteArray) -> bool:', `\tvar ${v.reader}: ContractMessage._WireReader = ContractMessage._WireReader.new(_bytes)`,
    `\twhile ${v.reader}.more():`, `\t\tvar ${v.tag}: int = ${v.reader}.tag()`, `\t\tvar ${v.wire}: int = ${v.tag} & 7`,
  );
  const skip = `${v.reader}.skip(${v.wire})`;
  if (def.fields.length === 0) {
    body.push(`\t\t${skip}`);
  } else {
    body.push(`\t\tmatch ${v.tag} >> 3:`);
    for (const field of def.fields) body.push(`\t\t\t${String(field.number)}:`, ...indent(w.decodeLines(field, v), 4));
    body.push('\t\t\t_:', `\t\t\t\t${skip}`);
  }
  body.push(`\treturn not ${v.reader}.failed`);
  if (rpc !== null) {
    const response = rpc.output === null ? 'ContractMessage' : w.ref(rpc.output);
    body.push(
      '', '', 'func request_name() -> String:', `\treturn ${quote(rpc.requestName)}`,
      '', '', 'func is_silent() -> bool:', `\treturn ${String(rpc.silent)}`,
      '', '', 'func is_retry() -> bool:', `\treturn ${String(rpc.retry)}`,
      '', '', 'func is_sensitive() -> bool:', `\treturn ${String(rpc.sensitive)}`,
      '', '', 'func new_response() -> ContractMessage:', `\treturn ${response}.new()`,
    );
  }
  return ['', '', `class ${def.name} extends ${base}:`, ...indent(body, 1)];
}

function kindsLines(kinds: readonly MessageDef[]): string[] {
  const entries = kinds.map((k) => `\t\tContractKind.new(${quote(k.name)}, ${k.name}, ${String(hasKeyField(k, 'id'))}),`);
  return ['', '', '## UserState kinds in kind order.', 'static func user_state_kinds() -> Array[ContractKind]:', '\tvar kinds: Array[ContractKind] = [', ...entries, '\t]', '\treturn kinds'];
}

function coreErrorsLines(model: Model): string[] {
  const out = ['', '', '## `GameError` values `(ogw.core_errors)` gives the core `rpc` of a request name, in written order.', 'static func core_errors(request_name: String) -> PackedInt32Array:'];
  if (model.coreErrors.length === 0) return [...out, '\treturn PackedInt32Array()'];
  out.push('\tmatch request_name:');
  for (const option of model.coreErrors) {
    out.push(`\t\t${quote(`core/${option.rpc}`)}:`, `\t\t\treturn PackedInt32Array([${option.names.map((n) => `GameError.${n}`).join(', ')}])`);
  }
  out.push('\treturn PackedInt32Array()');
  return out;
}

/** The `rpc` of each request message of a name space: an `rpc` of the name space's service first. */
function requestsOf(input: GodotInput, ns: Namespace): Map<MessageDef, RpcDef> {
  const requests = new Map<MessageDef, RpcDef>();
  const own = input.model.rpcs.filter((rpc) => rpc.service === SERVICE_OF[ns]);
  for (const rpc of [...own, ...input.model.rpcs]) {
    if (rpc.input !== null && !requests.has(rpc.input) && input.sets.namespaceOf.get(rpc.input) === ns) requests.set(rpc.input, rpc);
  }
  return requests;
}

function namespaceFile(input: GodotInput, namespaces: Record<Namespace, TypeDef[]>, ns: Namespace): string {
  const w = new Writer(ns, input.sets.namespaceOf);
  const types = namespaces[ns];
  const requests = requestsOf(input, ns);
  const lines = [HEADER, `class_name ${ns}`, 'extends RefCounted'];
  for (const def of types) if (def.kind === 'enum') lines.push(...enumLines(def));
  for (const def of types) if (def.kind === 'message') lines.push(...messageLines(w, def, requests.get(def) ?? null));
  if (ns === 'CoreContract' || ns === 'GameContract') lines.push(...kindsLines(userStateKinds(types)));
  if (ns === 'GameContract') lines.push(...coreErrorsLines(input.model));
  return `${lines.join('\n')}\n`;
}

/** `ContractJsonDev`: proto3 JSON of the UserState kinds and the messages they reach. */
class JsonWriter {
  private readonly namespaceOf: ReadonlyMap<TypeDef, Namespace>;

  constructor(namespaceOf: ReadonlyMap<TypeDef, Namespace>) {
    this.namespaceOf = namespaceOf;
  }

  ref(def: TypeDef): string {
    return `${this.namespaceOf.get(def) ?? 'GameContract'}.${def.name}`;
  }

  /** snake_case suffix of the private function names of a type: `GameContract.QuestUserState` → `game_contract_quest_user_state`. */
  key(def: TypeDef): string {
    return `${snakeCase(this.namespaceOf.get(def) ?? 'GameContract')}_${snakeCase(def.name)}`;
  }

  /** Expression of the JSON text of one value of a field (`v`). */
  valueText(field: FieldDef, v: string): string {
    const t = field.type;
    if (t.kind === 'message') return `_text_${this.key(t.def)}(${v})`;
    if (t.kind === 'enum') return `_enum_text_${this.key(t.def)}(${v})`;
    if (t.kind !== 'scalar') return '"0"';
    switch (t.scalar) {
      case 'int32': return `str(${v})`;
      case 'int64': return `JSON.stringify(str(${v}))`;
      case 'float': case 'double': return `_number_text(${v})`;
      case 'bool': return `"true" if ${v} else "false"`;
      case 'string': return `JSON.stringify(${v})`;
      default: return `_base64_text(${v})`;
    }
  }

  /** Condition under which a singular field is written: it is not the default value. */
  present(field: FieldDef, v: string): string {
    const t = field.type;
    if (t.kind === 'message') return `${v} != null`;
    if (t.kind === 'enum') return `${v} != 0`;
    if (t.kind !== 'scalar') return 'false';
    switch (t.scalar) {
      case 'float': case 'double': return `not ContractMessage._is_positive_zero(${v})`;
      case 'bool': return v;
      case 'string': case 'bytes': return `not ${v}.is_empty()`;
      default: return `${v} != 0`;
    }
  }

  textFunc(def: MessageDef): string[] {
    const out = ['', '', `static func _text_${this.key(def)}(m: ${this.ref(def)}) -> String:`, '\tvar parts: PackedStringArray = PackedStringArray()'];
    for (const field of def.fields) {
      const head = quote(`"${field.name}":`);
      if (field.repeated) {
        const t = field.type;
        const itemType = t.kind === 'message' ? this.ref(t.def) : t.kind === 'scalar' ? ({ int32: 'int', int64: 'int', float: 'float', double: 'float', bool: 'bool', string: 'String', bytes: 'PackedByteArray' }[t.scalar]) : 'int';
        out.push(
          `\tif not m.${field.name}.is_empty():`,
          '\t\tvar items: PackedStringArray = PackedStringArray()',
          `\t\tfor item: ${itemType} in m.${field.name}:`,
          `\t\t\titems.append(${this.valueText(field, 'item')})`,
          `\t\tparts.append(${head} + "[" + ",".join(items) + "]")`,
        );
      } else {
        out.push(`\tif ${this.present(field, `m.${field.name}`)}:`, `\t\tparts.append(${head} + ${this.valueText(field, `m.${field.name}`)})`);
      }
    }
    out.push('\treturn "{" + ",".join(parts) + "}"');
    return out;
  }

  /** Lines that read the JSON value `raw` of one value of a field into `<target>` or return false. */
  readValue(field: FieldDef, raw: string, assign: (value: string) => string): string[] {
    const t = field.type;
    if (t.kind === 'message') {
      const cls = this.ref(t.def);
      return [`var child: ${cls} = ${cls}.new()`, `if not _read_${this.key(t.def)}(child, ${raw}):`, '\treturn false', assign('child')];
    }
    if (t.kind === 'enum') {
      return [`var number: PackedInt64Array = _enum_of_${this.key(t.def)}(${raw})`, 'if number.is_empty():', '\treturn false', assign(field.repeated ? 'number[0]' : `number[0] as ${this.ref(t.def)}`)];
    }
    if (t.kind !== 'scalar') return ['return false'];
    switch (t.scalar) {
      case 'int32': case 'int64':
        return [`var number: PackedInt64Array = _int_of(${raw}, ${t.scalar === 'int32' ? '32' : '64'})`, 'if number.is_empty():', '\treturn false', assign('number[0]')];
      case 'float': case 'double':
        return [`var real: PackedFloat64Array = _float_of(${raw})`, 'if real.is_empty():', '\treturn false', assign('real[0]')];
      case 'bool':
        return [`if not (${raw} is bool):`, '\treturn false', `var flag: bool = ${raw}`, assign('flag')];
      case 'string':
        return [`if not (${raw} is String):`, '\treturn false', `var text: String = ${raw}`, assign('text')];
      default:
        return [`var raw_bytes: Array[PackedByteArray] = _bytes_of(${raw})`, 'if raw_bytes.is_empty():', '\treturn false', assign('raw_bytes[0]')];
    }
  }

  readFunc(def: MessageDef): string[] {
    const out = ['', '', '# ogw:input_boundary', `static func _read_${this.key(def)}(m: ${this.ref(def)}, data: Variant) -> bool:`, '\tm.decode(PackedByteArray())', '\tif not (data is Dictionary):', '\t\treturn false', '\tvar object: Dictionary = data'];
    for (const field of def.fields) {
      const camel = jsonName(field.name);
      out.push(`\tvar ${field.name}_json: Variant = _member(object, ${quote(field.name)}, ${quote(camel)})`, `\tif ${field.name}_json != null:`);
      if (field.repeated) {
        out.push(
          `\t\tif not (${field.name}_json is Array):`, '\t\t\treturn false',
          `\t\tvar ${field.name}_list: Array = ${field.name}_json`,
          `\t\tfor item: Variant in ${field.name}_list:`,
          ...indent(this.readValue(field, 'item', (v) => `m.${field.name}.append(${v})`), 3),
        );
      } else {
        out.push(...indent(this.readValue(field, `${field.name}_json`, (v) => `m.${field.name} = ${v}`), 2));
      }
    }
    out.push('\treturn true');
    return out;
  }

  enumFuncs(def: EnumDef): string[] {
    const key = this.key(def);
    const out = ['', '', `static func _enum_text_${key}(value: int) -> String:`, '\tmatch value:'];
    const seen = new Set<number>();
    for (const v of def.values) {
      if (seen.has(v.number)) continue;
      seen.add(v.number);
      out.push(`\t\t${String(v.number)}:`, `\t\t\treturn ${quote(JSON.stringify(v.name))}`);
    }
    out.push('\treturn str(value)', '', '', '# ogw:input_boundary', `static func _enum_of_${key}(raw: Variant) -> PackedInt64Array:`, '\tif raw is String:', '\t\tvar name: String = raw', '\t\tmatch name:');
    for (const v of def.values) out.push(`\t\t\t${quote(v.name)}:`, `\t\t\t\treturn PackedInt64Array([${String(v.number)}])`);
    out.push('\t\treturn PackedInt64Array()', '\treturn _int_of(raw, 32)');
    return out;
  }
}

/** Shared helpers of `ContractJsonDev`. */
const JSON_HELPERS = String.raw`

## JSON text of a float: proto3 JSON writes NaN and the infinities as strings.
static func _number_text(value: float) -> String:
	if is_nan(value):
		return "\"NaN\""
	if is_inf(value):
		return "\"Infinity\"" if value > 0.0 else "\"-Infinity\""
	return JSON.stringify(value)


## JSON string of the base64 of bytes.
static func _base64_text(value: PackedByteArray) -> String:
	return "\"\"" if value.is_empty() else JSON.stringify(Marshalls.raw_to_base64(value))


## The value of a field by proto name, or else by proto3 JSON name; null when there is neither.
# ogw:input_boundary
static func _member(object: Dictionary, name: String, json_name: String) -> Variant:
	if object.has(name):
		return object[name]
	if object.has(json_name):
		return object[json_name]
	return null


## A JSON integer (a number without a fraction or a decimal string) in the signed range of the given bits, as a list of one
## value; an empty list when it is not.
# ogw:input_boundary
static func _int_of(raw: Variant, bits: int) -> PackedInt64Array:
	var high: int = 0x7FFFFFFF if bits == 32 else 0x7FFFFFFFFFFFFFFF
	var low: int = -high - 1
	if raw is int:
		var whole: int = raw
		return PackedInt64Array([whole]) if whole >= low and whole <= high else PackedInt64Array()
	if raw is float:
		var real: float = raw
		if is_nan(real) or is_inf(real) or real != floorf(real) or absf(real) > 9007199254740991.0:
			return PackedInt64Array()
		var exact: int = int(real)
		return PackedInt64Array([exact]) if exact >= low and exact <= high else PackedInt64Array()
	if not (raw is String):
		return PackedInt64Array()
	var text: String = raw
	var negative: bool = text.begins_with("-")
	var digits: String = text.substr(1) if negative else text
	if digits.is_empty() or not digits.is_valid_int() or digits.begins_with("+") or digits.begins_with("-"):
		return PackedInt64Array()
	digits = digits.lstrip("0")
	var limit: String = str(high + 1) if negative and bits == 32 else str(high)
	if negative and bits == 64:
		limit = "9223372036854775808"
	if digits.length() > limit.length() or (digits.length() == limit.length() and digits > limit):
		return PackedInt64Array()
	if digits.is_empty():
		return PackedInt64Array([0])
	if negative and digits == "9223372036854775808":
		return PackedInt64Array([-0x7FFFFFFFFFFFFFFF - 1])
	var value: int = digits.to_int()
	return PackedInt64Array([-value if negative else value])


## A JSON number or one of the strings NaN, Infinity, -Infinity, or a decimal string, as a list of one value; an
## empty list when it is not.
# ogw:input_boundary
static func _float_of(raw: Variant) -> PackedFloat64Array:
	if raw is float:
		var real: float = raw
		return PackedFloat64Array([real])
	if raw is int:
		var whole: int = raw
		return PackedFloat64Array([float(whole)])
	if not (raw is String):
		return PackedFloat64Array()
	var text: String = raw
	match text:
		"NaN":
			return PackedFloat64Array([NAN])
		"Infinity":
			return PackedFloat64Array([INF])
		"-Infinity":
			return PackedFloat64Array([-INF])
	if not text.is_valid_float():
		return PackedFloat64Array()
	return PackedFloat64Array([text.to_float()])


## Bytes of a base64 string (standard or URL-safe alphabet, padding optional), as a list of one value; an empty list
## when it is not one.
# ogw:input_boundary
static func _bytes_of(raw: Variant) -> Array[PackedByteArray]:
	if not (raw is String):
		return []
	var text: String = raw
	text = text.replace("-", "+").replace("_", "/").rstrip("=")
	if text.length() % 4 == 1:
		return []
	for i: int in range(text.length()):
		var c: int = text.unicode_at(i)
		var letter: bool = (c >= 65 and c <= 90) or (c >= 97 and c <= 122) or (c >= 48 and c <= 57) or c == 43 or c == 47
		if not letter:
			return []
	if text.is_empty():
		var empty: Array[PackedByteArray] = [PackedByteArray()]
		return empty
	while text.length() % 4 != 0:
		text += "="
	var out: Array[PackedByteArray] = [Marshalls.base64_to_raw(text)]
	return out
`;

function jsonFile(input: GodotInput, namespaces: Record<Namespace, TypeDef[]>): string {
  const w = new JsonWriter(input.sets.namespaceOf);
  const kinds = [...userStateKinds(namespaces.CoreContract), ...userStateKinds(namespaces.GameContract)];
  const reached = reach(kinds);
  const messages = reached.filter((d): d is MessageDef => d.kind === 'message');
  const enums = reached.filter((d): d is EnumDef => d.kind === 'enum');
  const lines = [HEADER, 'class_name ContractJsonDev', 'extends RefCounted', '## proto3 JSON of the UserState kinds: proto field names, int64 as decimal strings, default values left out.'];
  lines.push('', '', '## JSON object text of a UserState kind message; an empty object for another message.', 'static func to_json(message: ContractMessage) -> String:');
  for (const def of messages) lines.push(`\tif message is ${w.ref(def)}:`, `\t\treturn _text_${w.key(def)}(message as ${w.ref(def)})`);
  lines.push('\treturn "{}"');
  lines.push(
    '', '', '## Puts every field of `message` back to its default value, then reads `json`. `false` when `json` is not that',
    '## message; unknown keys are left out.', 'static func from_json(message: ContractMessage, json: String) -> bool:',
    '\tvar parser: JSON = JSON.new()', '\tif parser.parse(json) != OK:', '\t\treturn false', '\tvar data: Variant = parser.data',
  );
  for (const def of messages) lines.push(`\tif message is ${w.ref(def)}:`, `\t\treturn _read_${w.key(def)}(message as ${w.ref(def)}, data)`);
  lines.push('\treturn false');
  for (const def of messages) lines.push(...w.textFunc(def), ...w.readFunc(def));
  for (const def of enums) lines.push(...w.enumFuncs(def));
  return `${lines.join('\n')}${JSON_HELPERS}`;
}

/** Files of the Godot client and client DEV generation targets, by path under the Godot project (`client/`). */
export function generateGodot(input: GodotInput): Map<string, string> {
  const namespaces = clientNamespaces(input.model, input.sets);
  const files = new Map<string, string>();
  for (const ns of ['CoreContract', 'GameContract', 'CoreCheatContract', 'GameCheatContract'] as const) {
    files.set(NAMESPACE_FILE[ns], namespaceFile(input, namespaces, ns));
  }
  files.set(JSON_FILE, jsonFile(input, namespaces));
  return files;
}
