/** Server generation target (`server/generated/contract/`) and server DEV generation target (`server/dev/generated/contract/`). */
import { posix } from 'node:path';
import { reach, type EnumDef, type FieldDef, type MessageDef, type Model, type RpcDef, type TypeDef } from '../model.ts';
import { pascalCase, snakeCase } from '../names.ts';
import { hasKeyField, kindStore, orderedKinds, VALIDATED_MODULE_MESSAGES } from '../rules/context.ts';
import { missingTables } from '../rules/fields.ts';
import type { Namespace, TypeSets } from '../typesets.ts';
import { WIRE_SOURCE } from './wire-source.ts';

export const SERVER_DIR = 'server/generated/contract';
export const SERVER_DEV_DIR = 'server/dev/generated/contract';

const NAMESPACE_FILE: Readonly<Record<Namespace, string>> = {
  CoreContract: `${SERVER_DIR}/core_contract.ts`,
  GameContract: `${SERVER_DIR}/game_contract.ts`,
  CoreCheatContract: `${SERVER_DEV_DIR}/core_cheat_contract.ts`,
  GameCheatContract: `${SERVER_DEV_DIR}/game_cheat_contract.ts`,
};
const WIRE_FILE = `${SERVER_DIR}/wire.ts`;
const DATA_FILE = 'server/generated/data/game_data.ts';
const CTX_FILE = 'server/core/storage/request_ctx.ts';

/** Service of the `rpc`s of each name space. */
const SERVICE_OF: Readonly<Record<Namespace, RpcDef['service']>> = {
  CoreContract: 'Core', GameContract: 'Game', CoreCheatContract: 'CoreCheat', GameCheatContract: 'Cheat',
};

const HEADER = '// Generated by the contract tool. Do not edit.\n';

export interface ServerInput {
  readonly model: Model;
  readonly sets: TypeSets;
  readonly tableNames: ReadonlySet<string>;
  readonly contractVersion: number;
  /** (kind, from version) in `GameContract.KINDS` order, then from version. */
  readonly converters: readonly { readonly kind: string; readonly from_version: number }[];
}

function importPath(from: string, to: string): string {
  const rel = posix.relative(posix.dirname(from), to);
  return rel.startsWith('.') ? rel : `./${rel}`;
}

function bigintLiteral(value: bigint): string {
  return `${String(value)}n`;
}

class FileWriter {
  private readonly input: ServerInput;
  private readonly ns: Namespace;
  private readonly lines: string[] = [];
  /** Messages whose rules this file declares, by rules constant name. */
  private readonly rulesDone = new Set<string>();

  constructor(input: ServerInput, ns: Namespace) {
    this.input = input;
    this.ns = ns;
  }

  private ref(def: TypeDef): string {
    const ns = this.input.sets.namespaceOf.get(def) ?? 'GameContract';
    return ns === this.ns ? def.name : `${ns}.${def.name}`;
  }

  /** Reference to an export of `CoreContract`. */
  private core(name: string): string {
    return this.ns === 'CoreContract' ? name : `CoreContract.${name}`;
  }

  private gameError(): string {
    return this.ns === 'GameContract' ? 'GameError' : 'GameContract.GameError';
  }

  private tsType(field: FieldDef): string {
    const t = field.type;
    let base: string;
    if (t.kind === 'scalar') {
      base = { int32: 'number', int64: 'bigint', float: 'number', double: 'number', bool: 'boolean', string: 'string', bytes: 'Uint8Array' }[t.scalar];
    } else if (t.kind === 'enum' || t.kind === 'message') {
      base = this.ref(t.def);
    } else {
      base = 'unknown';
    }
    if (field.repeated) return `${base}[]`;
    return t.kind === 'message' ? `${base} | null` : base;
  }

  private defaultValue(field: FieldDef): string {
    if (field.repeated) return '[]';
    const t = field.type;
    if (t.kind === 'message' || t.kind === 'unresolved') return 'null';
    if (t.kind === 'enum') {
      const zero = t.def.values.find((v) => v.number === 0) ?? t.def.values[0];
      return zero === undefined ? '0' : `${this.ref(t.def)}.${zero.name}`;
    }
    return { int32: '0', int64: '0n', float: '0', double: '0', bool: 'false', string: "''", bytes: 'new Uint8Array(0)' }[t.scalar];
  }

  private kind(field: FieldDef): string {
    const t = field.type;
    return t.kind === 'scalar' ? t.scalar : t.kind === 'enum' ? 'enum' : 'message';
  }

  private enumeration(def: EnumDef): void {
    this.lines.push('', `export const ${def.name} = {`);
    for (const value of def.values) this.lines.push(`  ${value.name}: ${String(value.number)},`);
    this.lines.push('} as const;', `export type ${def.name} = (typeof ${def.name})[keyof typeof ${def.name}];`);
  }

  private messageClass(def: MessageDef): void {
    const json = this.input.sets.json.has(def);
    this.lines.push('', `export class ${def.name} {`);
    for (const field of def.fields) this.lines.push(`  ${field.name}: ${this.tsType(field)} = ${this.defaultValue(field)};`);
    if (def.fields.length > 0) this.lines.push('');
    this.lines.push(
      '  encode(): Uint8Array {',
      `    return Wire.encode(this, schema_${def.name});`,
      '  }',
      '',
      `  static decode(bytes: Uint8Array): ${def.name} | null {`,
      `    return Wire.decode(bytes, schema_${def.name});`,
      '  }',
    );
    if (json) {
      this.lines.push(
        '',
        '  to_json(): unknown {',
        `    return Wire.to_json(this, schema_${def.name});`,
        '  }',
        '',
        `  static from_json(json: unknown): ${def.name} | null {`,
        `    return Wire.from_json(json, schema_${def.name});`,
        '  }',
      );
    }
    this.lines.push('}');
  }

  private schema(def: MessageDef): void {
    this.lines.push('', `const schema_${def.name}: Wire.Schema<${def.name}> = {`, `  create: () => new ${def.name}(),`);
    if (def.fields.length === 0) {
      this.lines.push('  fields: [],', '};');
      return;
    }
    this.lines.push('  fields: [');
    for (const field of def.fields) {
      let extra = '';
      if (field.type.kind === 'enum') extra = `, values: ${this.ref(field.type.def)}`;
      if (field.type.kind === 'message') extra = `, type: () => ${this.ref(field.type.def)}`;
      this.lines.push(`    { no: ${String(field.number)}, name: '${field.name}', kind: '${this.kind(field)}', repeated: ${String(field.repeated)}${extra} },`);
    }
    this.lines.push('  ],', '};');
  }

  private rulesName(def: MessageDef): string {
    return `rules_${this.input.sets.namespaceOf.get(def) ?? 'GameContract'}_${def.name}`;
  }

  private fieldRule(field: FieldDef): string | null {
    const { limits, table, unique } = field.rules;
    const kind = this.kind(field);
    const parts = [`name: '${field.name}'`, `kind: '${kind}'`, `repeated: ${String(field.repeated)}`];
    if (limits.min !== undefined) parts.push(`min: ${bigintLiteral(limits.min)}`);
    if (limits.max !== undefined) parts.push(`max: ${bigintLiteral(limits.max)}`);
    for (const rule of ['max_len', 'max_chars', 'min_count', 'max_count'] as const) {
      const value = limits[rule];
      if (value !== undefined) parts.push(`${rule}: ${String(value)}`);
    }
    if (unique) parts.push('unique: true');
    if (table !== null) parts.push(`table: (data, id) => Wire.has_id(data.${pascalCase(table)}Table, id)`);
    if (field.type.kind === 'enum') parts.push(`values: ${this.ref(field.type.def)}`);
    if (field.type.kind === 'message') parts.push(`rules: () => ${this.rulesName(field.type.def)}`);
    const checks = kind === 'string' || kind === 'enum' || kind === 'message' || parts.length > 3;
    return checks ? `  { ${parts.join(', ')} },` : null;
  }

  private rules(def: MessageDef): void {
    for (const reached of reach([def])) {
      if (reached.kind !== 'message') continue;
      const name = this.rulesName(reached);
      if (this.rulesDone.has(name)) continue;
      this.rulesDone.add(name);
      const rules = reached.fields.map((f) => this.fieldRule(f)).filter((r): r is string => r !== null);
      if (rules.length === 0) {
        this.lines.push('', `const ${name}: readonly Wire.Rule<GameData.DataSet>[] = [];`);
      } else {
        this.lines.push('', `const ${name}: readonly Wire.Rule<GameData.DataSet>[] = [`, ...rules, '];');
      }
    }
  }

  private validator(def: MessageDef): void {
    this.rules(def);
    this.lines.push(
      '',
      `export function validate_${def.name}(message: ${def.name}, data: GameData.DataSet): ${this.core('ValidationFailure')} | null {`,
      `  return Wire.validate(message, ${this.rulesName(def)}, data, '');`,
      '}',
    );
  }

  /** True when every `table` option the request reaches names a table of the server build target. */
  private tablesPresent(def: MessageDef): boolean {
    return missingTables(def, this.input.tableNames).length === 0;
  }

  private rpcs(): MessageDef[] {
    const service = SERVICE_OF[this.ns];
    const rpcs = this.input.model.rpcs.filter((r) => r.service === service);
    const validated: MessageDef[] = [];
    const entries: string[] = [];
    for (const rpc of rpcs) {
      const input = rpc.input;
      const output = rpc.output;
      if (input === null || output === null) continue;
      const hasValidator = rpc.file.pkg === 'game' || this.tablesPresent(input);
      if (hasValidator) validated.push(input);
      const errors = (rpc.errors ?? []).map((e) => `${this.gameError()}.${e}`).join(', ');
      // A message without fields has the type of the parameter: no assertion.
      const message = input.fields.length === 0 ? 'message' : `message as ${this.ref(input)}`;
      const validate = hasValidator ? `(message, data) => validate_${input.name}(${message}, data)` : 'null';
      entries.push(
        '  {',
        `    name: '${rpc.requestName}',`,
        `    request_class: ${this.ref(input)},`,
        `    response_class: ${this.ref(output)},`,
        `    silent: ${String(rpc.silent)},`,
        `    retry: ${String(rpc.retry)},`,
        `    sensitive: ${String(rpc.sensitive)},`,
        `    errors: [${errors}],`,
        `    validate: ${validate},`,
        '  },',
      );
    }
    this.lines.push('', `export const RPCS: readonly ${this.core('RpcInfo')}[] = [`, ...entries, '];');
    return validated;
  }

  private handlerTypes(): void {
    const service = SERVICE_OF[this.ns];
    for (const rpc of this.input.model.rpcs.filter((r) => r.service === service)) {
      if (rpc.input === null || rpc.output === null) continue;
      const errors = (rpc.errors ?? []).map((e) => `typeof ${this.gameError()}.${e}`);
      this.lines.push(
        '',
        `export type ${rpc.name}Error = ${errors.length === 0 ? 'never' : errors.join(' | ')};`,
        `export type ${rpc.name}Handler = (ctx: RequestCtx, request: ${this.ref(rpc.input)}) => ${this.ref(rpc.output)} | ${rpc.name}Error;`,
      );
    }
  }

  private kinds(): void {
    const kinds = orderedKinds(this.input.sets.byNamespace[this.ns]);
    const entries = kinds.map((def) => {
      const isList = hasKeyField(def, 'id');
      return `  { name: '${def.name}', kind_class: ${def.name}, store: '${String(kindStore(def))}', column: '${snakeCase(def.name)}', is_list: ${String(isList)}, is_public: ${String(def.isPublic)} },`;
    });
    this.lines.push('', `export const KINDS: readonly ${this.core('KindInfo')}[] = [`, ...entries, '];');
  }

  private coreInterfaces(): void {
    this.lines.push(
      '',
      'export interface RpcInfo {',
      '  readonly name: string;',
      '  readonly request_class: { new (): { encode(): Uint8Array }; decode(bytes: Uint8Array): { encode(): Uint8Array } | null };',
      '  readonly response_class: { new (): { encode(): Uint8Array }; decode(bytes: Uint8Array): { encode(): Uint8Array } | null };',
      '  readonly silent: boolean;',
      '  readonly retry: boolean;',
      '  readonly sensitive: boolean;',
      '  readonly errors: readonly number[];',
      '  readonly validate: ((message: { encode(): Uint8Array }, data: GameData.DataSet) => ValidationFailure | null) | null;',
      '}',
      '',
      'export interface ValidationFailure {',
      '  readonly path: string;',
      '  readonly rule: string;',
      '}',
      '',
      'export interface KindInfo {',
      '  readonly name: string;',
      '  readonly kind_class: { new (): { encode(): Uint8Array }; decode(bytes: Uint8Array): { encode(): Uint8Array } | null };',
      "  readonly store: 'user_state' | 'server_state' | 'game_state';",
      '  readonly column: string;',
      '  readonly is_list: boolean;',
      '  readonly is_public: boolean;',
      '}',
    );
  }

  private gameExtras(): void {
    const entries = this.input.model.coreErrors.map((o) => `  ['core/${o.rpc}', [${o.names.map((n) => `GameError.${n}`).join(', ')}]],`);
    this.lines.push(
      '',
      'export const CORE_ERRORS: ReadonlyMap<string, readonly GameError[]> = new Map<string, readonly GameError[]>([',
      ...entries,
      ']);',
      '',
      `export const CONTRACT_VERSION: number = ${String(this.input.contractVersion)};`,
      '',
      'export const CONVERTERS: readonly { kind: string; from_version: number }[] = [',
      ...this.input.converters.map((c) => `  { kind: '${c.kind}', from_version: ${String(c.from_version)} },`),
      '];',
    );
  }

  private moduleMessages(): MessageDef[] {
    if (this.ns !== 'GameContract') return [];
    return [...VALIDATED_MODULE_MESSAGES].map((n) => this.input.model.types.game.get(n)).filter((d): d is MessageDef => d?.kind === 'message');
  }

  private imports(path: string, body: string): string[] {
    const out: string[] = [];
    const uses = (name: string): boolean => new RegExp(`\\b${name}\\.`).test(body);
    if (uses('Wire')) out.push(`import * as Wire from '${importPath(path, WIRE_FILE)}';`);
    for (const ns of ['CoreContract', 'CoreCheatContract', 'GameContract'] as const) {
      if (ns !== this.ns && uses(ns)) out.push(`import * as ${ns} from '${importPath(path, NAMESPACE_FILE[ns])}';`);
    }
    if (uses('GameData')) out.push(`import type * as GameData from '${importPath(path, DATA_FILE)}';`);
    if (/\bRequestCtx\b/.test(body)) out.push(`import type { RequestCtx } from '${importPath(path, CTX_FILE)}';`);
    return out;
  }

  write(): string {
    const types = this.input.sets.byNamespace[this.ns];
    const enums = types.filter((d): d is EnumDef => d.kind === 'enum');
    const messages = types.filter((d): d is MessageDef => d.kind === 'message');
    if (this.ns === 'CoreContract') this.coreInterfaces();
    for (const def of enums) this.enumeration(def);
    for (const def of messages) this.messageClass(def);
    for (const def of messages) this.schema(def);
    const validated = [...this.rpcs(), ...this.moduleMessages()];
    for (const def of validated) this.validator(def);
    if (this.ns === 'GameContract' || this.ns === 'GameCheatContract') this.handlerTypes();
    if (this.ns === 'CoreContract' || this.ns === 'GameContract') this.kinds();
    if (this.ns === 'GameContract') this.gameExtras();
    const body = this.lines.join('\n');
    const path = NAMESPACE_FILE[this.ns];
    return `${HEADER}${this.imports(path, body).join('\n')}\n${body}\n`;
  }
}

/** Files of the server and server DEV generation targets, by path under the game folder. */
export function generateServer(input: ServerInput): Map<string, string> {
  const files = new Map<string, string>();
  files.set(WIRE_FILE, WIRE_SOURCE);
  for (const ns of ['CoreContract', 'GameContract', 'CoreCheatContract', 'GameCheatContract'] as const) {
    files.set(NAMESPACE_FILE[ns], new FileWriter(input, ns).write());
  }
  files.set(`${SERVER_DIR}/contract_version`, `${String(input.contractVersion)}\n`);
  files.set(`${SERVER_DIR}/converters.json`, `${JSON.stringify(input.converters, null, 2)}\n`);
  return files;
}
